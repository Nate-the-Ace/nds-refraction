// Bakes the 100 generated levels (5 tiers x 20) into src/levels_gen.js.
// node tools/gen_levels.js
const fs=require('fs'),path=require('path');
const E=require('../src/engine.js');const {makeGen}=require('../src/gen.js');
const G=makeGen(E);
const out=[],names=new Set(),count={};
const score=lv=>lv.pieces.filter(p=>!p.fixed).length*3+lv.pieces.filter(p=>p.t==='goal').length*2+lv.pieces.filter(p=>p.t==='wall').length;
for(let tier=1;tier<=5;tier++){
  const fams=G.familiesFor(tier),want=[];
  // balanced family mix: cycle through the families
  for(let k=0;k<20;k++)want.push(fams[k%fams.length]);
  // glass balls and lenses are a must: guaranteed minimum per tier
  const MIN={orb:4,zoom:2,spread:1,focus:2};
  for(const f in MIN){
    let o=want.filter(x=>x===f).length;
    for(let k=19;o<MIN[f]&&k>=0;k--)if(!(f in MIN&&want[k] in MIN)&&want[k]!==f){want[k]=f;o++}
  }
  const lvs=[];
  want.forEach((fam,k)=>{
    for(let a=0;a<400;a++){
      const seed=tier*10000+k*131+a;
      const lv=G.make(seed,tier,fam);
      if(!lv)continue;
      if(names.has(lv.name))continue;
      names.add(lv.name);lv.seed=seed;lvs.push(lv);break;
    }
  });
  if(lvs.length!==20){console.log('tier',tier,'short; wanted',want.join(','),'got',lvs.map(l=>l.family).join(','));process.exit(1)}
  lvs.sort((a,b)=>score(a)-score(b));
  if(tier===1){const i=lvs.findIndex(l=>l.family==='orb');lvs.unshift(lvs.splice(i,1)[0])}
  for(const lv of lvs){count[lv.family]=(count[lv.family]||0)+1;out.push(lv)}
}
const strip=lv=>({name:lv.name,hint:lv.hint,pieces:lv.pieces,sol:lv.sol,...(lv.pol?{pol:1}:{}),...(lv.coh?{coh:1}:{})});
const body=out.map(lv=>'/*'+lv.family+' '+lv.seed+'*/'+JSON.stringify(strip(lv))).join(',\n');
fs.writeFileSync(path.join(__dirname,'../src/levels_gen.js'),
'// Generated by tools/gen_levels.js. Do not edit by hand.\nconst GEN_LEVELS=[\n'+body+'\n];\nif(typeof module!==\'undefined\')module.exports={GEN_LEVELS};\n');
console.log(out.length,'levels',JSON.stringify(count));
